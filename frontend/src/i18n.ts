export const translations: Record<Language, Record<string, string>> = { en, lt }

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  let value = translations[language][key] ?? translations.en[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([name, replacement]) => {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
    })
  }
  return value
}

export function formatPrice(value: number, language: Language): string {
  return new Intl.NumberFormat(language === 'lt' ? 'lt-LT' : 'en-IE', {
    style: 'currency',
    currency: 'EUR',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(value)
}
